package com.duties

import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.tasks.await

/** Thrown when google-services.json has no web client id yet (SHA-1 not added / file not refreshed). */
class MissingWebClientIdException : Exception("default_web_client_id is missing")

/** The web client id is generated by the google-services plugin from google-services.json. */
private fun webClientId(context: Context): String? {
    val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
    return if (id == 0) null else context.getString(id)
}

/** Google account picker -> Firebase credential -> Firebase sign-in. */
suspend fun signInWithGoogle(context: Context) {
    val clientId = webClientId(context) ?: throw MissingWebClientIdException()

    val option = GetSignInWithGoogleOption.Builder(clientId).build()
    val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
    val result = CredentialManager.create(context).getCredential(context, request)

    val credential = result.credential
    if (credential is CustomCredential &&
        credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
    ) {
        val idToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
        FirebaseAuth.getInstance()
            .signInWithCredential(GoogleAuthProvider.getCredential(idToken, null))
            .await()
    } else {
        throw IllegalStateException("Unexpected credential type")
    }
}

suspend fun signOut(context: Context) {
    // this phone stops receiving the notifications of the account (needs the login, so it comes first)
    Push.unregisterToken()
    try {
        CredentialManager.create(context).clearCredentialState(ClearCredentialStateRequest())
    } catch (_: Exception) {
        // not important, we still sign out of Firebase below
    }
    FirebaseAuth.getInstance().signOut()
}
